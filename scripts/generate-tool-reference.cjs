#!/usr/bin/env node
const fs = require('node:fs');
const path = require('node:path');
const manifest = require('../addons/godot_universal_mcp/tool_manifest.json');
const lines = ['# Bridge tool reference', '', '<!-- Generated by scripts/generate-tool-reference.cjs. Do not edit by hand. -->', '',
  'These public MCP tools are generated from `addons/godot_universal_mcp/tool_manifest.json`.',
  'MCP `tools/list` provides their complete, self-contained JSON schemas. Unknown parameters are rejected on both sides.',
  'Optional features may return `WRITE_DISABLED`, `TOOL_NOT_AVAILABLE` or `NOT_IMPLEMENTED`; an advertised schema does not grant permission.', '',
  '| MCP tool | Private command or workflow | Risk | Required parameters |',
  '| --- | --- | --- | --- |'];
for (const tool of manifest.tools) lines.push(`| \`${tool.name}\` | \`${tool.command || `workflow:${tool.operation}`}\` | ${tool.risk} | ${(tool.required || []).join(', ') || 'None'} |`);
lines.push('', 'The remaining managed-process and offline tools are enumerated by MCP `tools/list`.',
  '`godot_run_project` is an ordinary development launch, **not isolated validation**.',
  '`godot_runtime_logs` reads only this server context\'s managed-process output; `godot_runtime_bridge_logs` is the separate live bridge capability.', '',
  'See [BRIDGE_GUIDE.md](BRIDGE_GUIDE.md) for paths, bounds, permissions, lifecycle and readiness semantics.', '');
const content = lines.join('\n');
const output = path.resolve(__dirname, '../docs/TOOL_REFERENCE.md');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(output, 'utf8') !== content) { console.error('Tool reference is stale. Run node scripts/generate-tool-reference.cjs'); process.exitCode = 1; }
} else fs.writeFileSync(output, content);
